"""Write runtime/kvf_lowrank_inst.cu: extern "C" wrappers for every low-rank kernel
variant the WSL harness may launch (head-major, contiguous)."""
lines = ['// kvf_lowrank_inst.cu - generated by tools/gen_lowrank_inst.py: extern "C" entry points',
         '// for the low-rank-key decode kernels, so the WSL harness loads them by plain name.',
         '#include "kvf_lowrank.cuh"', 'using namespace kvf;', '']
fmts = {"f16_f16": ("FMT_F16", "FMT_F16"), "int8_int8": ("FMT_INT8", "FMT_INT8"), "int8_int4": ("FMT_INT8", "FMT_INT4")}
ranks = {128: [64, 128], 64: [32, 64]}
for D, rs in ranks.items():
    lines.append('extern "C" __global__ void merge_d%d(const Args a) { decode_merge_body<%d>(a); }' % (D, D))
    for R in rs:
        lines.append('extern "C" __global__ void proj_d%d_r%d(const float *q, const float *Bp, float *q_lr, int H, int Hkv) { project_q_body<%d, %d>(q, Bp, q_lr, H, Hkv); }' % (D, R, D, R))
        for fn, (kfe, vfe) in fmts.items():
            for G in (1, 2, 4, 8):
                for U in (2, 4, 8):
                    for fin in (0, 1):
                        # mb: minimum resident 256-thread blocks per SM. Capping registers
                        # (mb 3 = 85, mb 4 = 64) spilled and ran 30-150x slower, so only 1.
                        for mb in (1,):
                            name = "lr_%s_d%d_r%d_g%d_u%d_mb%d_%s" % (fn, D, R, G, U, mb, "final" if fin else "part")
                            lines.append('extern "C" __global__ void __launch_bounds__(256, %d) %s(const Args a, int kgs) { decode_partial_lr_body<%s, %s, %d, %d, %d, %d, ORD_HEAD, %s>(a, kgs); }'
                                         % (mb, name, kfe, vfe, D, R, G, U, "true" if fin else "false"))
open("runtime/kvf_lowrank_inst.cu", "w").write("\n".join(lines) + "\n")
print(len(lines), "lines")
