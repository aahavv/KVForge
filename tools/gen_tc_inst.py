"""Write runtime/kvf_tc_inst.cu: extern "C" wrappers for the tensor-core GQA decode
kernels (runtime/kvf_tc.cuh), loaded by name from the WSL harness."""
lines = ['// kvf_tc_inst.cu - generated by tools/gen_tc_inst.py', '#include "kvf_tc.cuh"', 'using namespace kvf;', '']
fmts = {"int8_int8": ("FMT_INT8", "FMT_INT8"), "int8_int4": ("FMT_INT8", "FMT_INT4")}
for D in (64, 128):
    lines.append('extern "C" __global__ void merge_rot_d%d(const Args a, const float *signs) { decode_merge_rot_body<%d>(a, signs); }' % (D, D))
    for fn, (kf, vf) in fmts.items():
        for U in (1, 2, 0):   # rotated variants: split path only (the merge rotates back)
            name = "tc_rot_%s_d%d_u%d_part" % (fn, D, U)
            lines.append('extern "C" __global__ void __launch_bounds__(256) %s(const Args a, int kgs, const float *signs) { decode_tc_body<%s, %s, %d, %d, false, true, %s>(a, kgs, signs); }'
                         % (name, kf, vf, D, max(U, 1), "true" if U == 0 else "false"))
        for U in (1, 2, 0):   # U = 0 names the software-pipelined loop (one tile per stage)
            for fin in (0, 1):
                name = "tc_%s_d%d_u%d_%s" % (fn, D, U, "final" if fin else "part")
                lines.append('extern "C" __global__ void __launch_bounds__(256) %s(const Args a, int kgs) { decode_tc_body<%s, %s, %d, %d, %s, false, %s>(a, kgs); }'
                             % (name, kf, vf, D, max(U, 1), "true" if fin else "false", "true" if U == 0 else "false"))
open("runtime/kvf_tc_inst.cu", "w").write("\n".join(lines) + "\n")
print(len(lines), "lines")
